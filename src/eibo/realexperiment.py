"""Fixed-observable temporal experiments, with explicitly conditional floors.

No independence, session assignment or real-data coverage is inferred here.
All class selection, priors, windows and representations come from the pilot plan.
"""

from __future__ import annotations

import collections

import numpy as np

from .realdata import whole_interval_mask
from .riskcert import direct_risk_bounds, empirical_known_risk, joint_radius_from_change_budget
from .statcore import DEFAULT_MAX_SIZE, grid_cardinality, quantize, symbol_to_id

PERIODS = ("pilot", "certificate", "evaluation")


class FixedPrefixEncoder:
    """Vectorized lookup whose entries are generated by the canonical codec."""

    def __init__(self, k, bins):
        self.k, self.bins = int(k), int(bins)
        self.base = grid_cardinality("log", log_bins=self.bins)
        self.alphabet = self.base ** self.k
        if self.k < 1 or self.alphabet > 1048576:
            raise ValueError("prefix alphabet is outside this experiment's memory budget")
        self.lookup = np.zeros((2, DEFAULT_MAX_SIZE + 1), dtype=np.int64)
        for direction in (0, 1):
            for size in range(1, DEFAULT_MAX_SIZE + 1):
                self.lookup[direction, size] = symbol_to_id(
                    quantize([(direction, size)], 1, "log", log_bins=self.bins),
                    "log", log_bins=self.bins)
        # The canonical log codec saturates above max_size. Verify the adapter.
        for direction in (0, 1):
            above = symbol_to_id(quantize([(direction, DEFAULT_MAX_SIZE + 1)], 1,
                                         "log", log_bins=self.bins), "log", log_bins=self.bins)
            if above != self.lookup[direction, DEFAULT_MAX_SIZE]:
                raise RuntimeError("canonical overflow mapping changed")

    def encode(self, ppi):
        values = np.asarray(ppi)
        if values.ndim != 3 or values.shape[1] != 3 or values.shape[2] < self.k:
            raise ValueError("expected PPI shape (records, 3, capacity>=k)")
        direction, size = values[:, 1, :self.k], values[:, 2, :self.k]
        if not np.all(np.isin(direction, [-1, 1])):
            raise ValueError("usable prefix contains a direction other than -1/+1; refusing to change the audited population")
        if not np.all(np.isfinite(size)) or np.any(size <= 0) or np.any(size != np.floor(size)):
            raise ValueError("usable prefix contains a nonpositive/noninteger size; refusing to change the audited population")
        # +1 is the forward/client direction (canonical code 0); -1 is reverse.
        digits = self.lookup[(direction < 0).astype(np.int64), np.minimum(size, DEFAULT_MAX_SIZE).astype(np.int64)]
        result = np.zeros(len(values), dtype=np.int64)
        for column in range(self.k):
            result = result * self.base + digits[:, column]
        return result


def fine_to_coarse_ids(k):
    """Map log M=2 prefixes to log M=1 using the canonical direction IDs."""
    fine_base = grid_cardinality("log", log_bins=2)
    coarse_base = grid_cardinality("log", log_bins=1)
    direction_ids = [symbol_to_id((direction, ("log", 0)), "log", log_bins=1) for direction in (0, 1)]
    values = np.arange(fine_base ** k, dtype=np.int64)
    result = np.zeros(len(values), dtype=np.int64)
    for column in range(k):
        digit = (values // (fine_base ** (k - column - 1))) % fine_base
        result = result * coarse_base + np.asarray(direction_ids)[digit // 2]
    return result


class TimeUnitGeometry:
    """Global UTC blocks, coarsened whenever one rounded flow crosses blocks.

    This repairs within-flow splitting only. It does not remove dependence
    between distinct flows or establish unbiasedness conditional on geometry.
    """

    def __init__(self, window, services, widths, rounding):
        self.window, self.widths, self.rounding = window, tuple(widths), rounding
        self.hour_origin = int(window[0] // 3600)
        self.hours = np.zeros((int(np.ceil(window[1] / 3600)) - self.hour_origin, services), dtype=np.int64)
        self.origins, self.bridges = {}, {}
        for width in self.widths:
            self.origins[width] = int(window[0] // width)
            blocks = int(np.ceil(window[1] / width)) - self.origins[width]
            self.bridges[width] = np.zeros(blocks + 1, dtype=np.int64)

    def add(self, first, last, selected_first, selected_labels):
        if len(selected_first):
            hour = np.floor(selected_first / 3600).astype(np.int64) - self.hour_origin
            np.add.at(self.hours, (hour, selected_labels), 1)
        upper = np.asarray(last) + self.rounding
        if self.rounding > 0:
            upper = np.nextafter(upper, -np.inf)
        for width in self.widths:
            left = np.floor(first / width).astype(np.int64) - self.origins[width]
            right = np.floor(upper / width).astype(np.int64) - self.origins[width]
            cross = right > left
            # Edge j joins block j with block j+1. Interval [left,right)
            # marks every edge that must be merged. Include unselected flows.
            np.add.at(self.bridges[width], left[cross], 1)
            np.add.at(self.bridges[width], right[cross], -1)

    def diagnostics(self, priors, alpha):
        ns = self.hours.sum(axis=0)
        if np.any(ns == 0):
            raise ValueError("selected service absent from time-unit counts")
        result = []
        epochs = (np.arange(len(self.hours)) + self.hour_origin) * 3600
        for width in self.widths:
            blocks = len(self.bridges[width]) - 1
            block_counts = np.zeros((blocks, len(ns)), dtype=np.int64)
            np.add.at(block_counts, epochs // width - self.origins[width], self.hours)
            linked = np.cumsum(self.bridges[width])[:max(0, blocks - 1)] > 0
            component = np.concatenate(([0], np.cumsum(~linked))).astype(np.int64)
            merged_counts = np.zeros((int(component[-1]) + 1, len(ns)), dtype=np.int64)
            np.add.at(merged_counts, component, block_counts)
            naive_change = (block_counts * (priors / ns)).sum(axis=1)
            merged_change = (merged_counts * (priors / ns)).sum(axis=1)
            budgets = [float(np.dot(naive_change, naive_change)), float(np.dot(merged_change, merged_change))]
            radii = joint_radius_from_change_budget(budgets, alpha=alpha)
            result.append({"block_seconds": width,
                           "start_assigned_nonempty_blocks": int(np.any(block_counts > 0, axis=1).sum()),
                           "span_merged_nonempty_units": int(np.any(merged_counts > 0, axis=1).sum()),
                           "merged_boundary_edges": int(linked.sum()),
                           "start_assigned_squared_change_budget": budgets[0],
                           "span_merged_squared_change_budget": budgets[1],
                           "start_assigned_radius_if_assumptions_hold": float(radii[0]),
                           "span_merged_radius_if_assumptions_hold": float(radii[1]),
                           "status": "conditional_sensitivity_only; independence and conditional unbiasedness unverified"})
        return result


class RealExperimentCounts:
    def __init__(self, plan, tables, *, time_scale, widths):
        if plan["status"] != "prepared" or not plan["full_scan"]:
            raise ValueError("a complete prepared audit is required")
        self.plan, self.k, self.time_scale = plan, int(plan["k"]), time_scale
        self.known = np.asarray(plan["known_service_codes"], dtype=np.int64)
        if len(self.known) < 2 or np.any(np.diff(self.known) <= 0):
            raise ValueError("known APP codes must be sorted and distinct")
        self.priors = np.full(len(self.known), plan["known_prior_per_service"])
        self.encoders = {rung: FixedPrefixEncoder(self.k, rung) for rung in (1, 2)}
        expected_representations = [{"scheme": "log", "M": rung, "k": self.k,
                                     "alphabet_size": codec.alphabet} for rung, codec in self.encoders.items()]
        if plan["fixed_representations"] != expected_representations:
            raise ValueError("plan representations differ from the fixed experiment")
        self.begin = min(t["day_seconds"] for t in tables)
        self.end = max(t["day_seconds"] for t in tables) + 86400
        self.windows = {p: (plan["windows"][p]["start_epoch"], plan["windows"][p]["end_epoch"]) for p in PERIODS}
        self.rounding = plan["time_rounding_envelope_seconds"]
        self.counts = {p: {rung: np.zeros((len(self.known), codec.alphabet), dtype=np.int64)
                           for rung, codec in self.encoders.items()} for p in PERIODS}
        self.period_service = {p: collections.Counter() for p in PERIODS}
        self.geometry = {p: TimeUnitGeometry(self.windows[p], len(self.known), widths, self.rounding)
                         for p in ("certificate", "evaluation")}
        self.rows_read = 0
        self.refinement = fine_to_coarse_ids(self.k)

    def add(self, records, capacity):
        self.rows_read += len(records)
        first = np.asarray(records["TIME_FIRST"], dtype=float) / self.time_scale
        last = np.asarray(records["TIME_LAST"], dtype=float) / self.time_scale
        lengths, labels = np.asarray(records["PPI_LEN"], dtype=float), np.asarray(records["APP"])
        usable = (np.isfinite(first) & np.isfinite(last) & (last >= first) &
                  (first >= self.begin) & (first < self.end) & np.isfinite(lengths) &
                  (lengths == np.floor(lengths)) & (lengths >= self.k) & (lengths <= capacity))
        for period, window in self.windows.items():
            all_mask = usable & whole_interval_mask(first, last, window, self.rounding)
            keys, numbers = np.unique(labels[all_mask], return_counts=True)
            self.period_service[period].update({int(key): int(n) for key, n in zip(keys, numbers)})
            mask = all_mask & np.isin(labels, self.known)
            selected_labels = np.searchsorted(self.known, labels[mask])
            for rung, codec in self.encoders.items():
                symbols = codec.encode(records["PPI"][mask])
                np.add.at(self.counts[period][rung], (selected_labels, symbols), 1)
            if period in self.geometry:
                self.geometry[period].add(first[all_mask], last[all_mask], first[mask], selected_labels)

    def reconcile(self, expected):
        for period in PERIODS:
            if self.period_service[period] != collections.Counter(expected[period]):
                raise ValueError(f"full audited service-count reconciliation failed: {period}")
            for service in self.known:
                actual = self.period_service[period][int(service)]
                if actual != expected[period][int(service)] or actual <= 0:
                    raise ValueError(f"audited count mismatch/empty service: {period}, APP={service}, actual={actual}, expected={expected[period][int(service)]}")
            projected = np.zeros_like(self.counts[period][1])
            for column, coarse in enumerate(self.refinement):
                projected[:, coarse] += self.counts[period][2][:, column]
            if not np.array_equal(projected, self.counts[period][1]):
                raise RuntimeError("M=2 to M=1 refinement reconciliation failed")
            if period in self.geometry and not np.array_equal(self.geometry[period].hours.sum(axis=0), self.counts[period][1].sum(axis=1)):
                raise RuntimeError("time-unit and symbol-count reconciliation failed")


def histogram_predictions(counts, priors):
    laws = counts / counts.sum(axis=1)[:, None]
    scores = priors[:, None] * laws
    # APP order is fixed by pilot; np.argmax resolves ties to the first APP.
    return scores.argmax(axis=0), np.all(counts == 0, axis=0)


def classifier_metrics(counts, priors, predictions, unseen):
    laws = counts / counts.sum(axis=1)[:, None]
    successes = (laws * (predictions[None, :] == np.arange(len(counts))[:, None])).sum(axis=1)
    return {"known_weighted_error": float(np.dot(priors, 1 - successes)),
            "per_service_error": (1 - successes).tolist(),
            "per_service_unseen_symbol_mass": laws[:, unseen].sum(axis=1).tolist(),
            "known_weighted_unseen_symbol_mass": float(np.dot(priors, laws[:, unseen].sum(axis=1)))}


def empirical_drift(left, right, priors):
    laws_left, laws_right = left / left.sum(axis=1)[:, None], right / right.sum(axis=1)[:, None]
    tv = 0.5 * np.abs(laws_left - laws_right).sum(axis=1)
    return {"per_service_empirical_tv": tv.tolist(), "prior_weighted_empirical_tv": float(np.dot(priors, tv)),
            "status": "descriptive empirical shift; no population-TV or deployment-risk certificate"}


def analyze_counts(experiment):
    priors, alpha = experiment.priors, experiment.plan["alpha"]
    geometry = {period: item.diagnostics(priors, alpha) for period, item in experiment.geometry.items()}
    rows = []
    for rung, codec in experiment.encoders.items():
        counts = {p: experiment.counts[p][rung] for p in PERIODS}
        pilot_prediction, pilot_unseen = histogram_predictions(counts["pilot"], priors)
        certificate_prediction, certificate_unseen = histogram_predictions(counts["certificate"], priors)
        periods = {}
        for period in PERIODS:
            point = empirical_known_risk(counts[period], priors)
            periods[period] = {"sample_counts": counts[period].sum(axis=1).tolist(),
                               "empirical_known_bayes_risk": point,
                               "pilot_classifier": classifier_metrics(counts[period], priors, pilot_prediction, pilot_unseen)}
            if period in geometry:
                periods[period]["iid_floors_if_assumptions_hold"] = direct_risk_bounds(counts[period], priors, alphabet_size=codec.alphabet, alpha=alpha)
                periods[period]["time_unit_sensitivity"] = [dict(item,
                    start_assigned_lower_floor_if_assumptions_hold=max(0.0, point - item["start_assigned_radius_if_assumptions_hold"]),
                    span_merged_lower_floor_if_assumptions_hold=max(0.0, point - item["span_merged_radius_if_assumptions_hold"]))
                                                             for item in geometry[period]]
        # This second model is fixed before evaluation, offering a recency comparison.
        periods["evaluation"]["certificate_classifier"] = classifier_metrics(counts["evaluation"], priors, certificate_prediction, certificate_unseen)
        rows.append({"M": rung, "k": experiment.k, "alphabet_size": codec.alphabet, "periods": periods,
                     "drift": {name: empirical_drift(counts[a], counts[b], priors) for name, a, b in
                               (("pilot_to_certificate", "pilot", "certificate"),
                                ("certificate_to_evaluation", "certificate", "evaluation"),
                                ("pilot_to_evaluation", "pilot", "evaluation"))}})
    loss = {p: rows[0]["periods"][p]["empirical_known_bayes_risk"] - rows[1]["periods"][p]["empirical_known_bayes_risk"] for p in PERIODS}
    if any(value < -1e-12 for value in loss.values()):
        raise RuntimeError("empirical risk increased under a deterministic refinement")
    return {"status": "exploratory; real-data coverage not measured", "known_service_codes": experiment.known.tolist(),
            "known_priors": priors.tolist(), "unknown_prior": experiment.plan["unknown_prior"], "alpha_per_fixed_comparison": alpha,
            "representations": rows, "empirical_coarsening_loss_M1_minus_M2": loss,
            "scope": "known-class weighted error contribution only; unknown-class error discarded; target is the audited filtered flow population",
            "assumptions_established": False,
            "interpretation": ["Empirical Bayes risk is a sample functional; its true population value is unknown.",
                               "Every floor is conditional on its listed independence/unbiasedness assumptions, which this data does not establish.",
                               "No maximum across representations, block widths or methods is certified; alpha is per fixed comparison.",
                               "Empirical temporal TV and coarsening loss include sampling error and are not population certificates.",
                               "A certificate-period floor is not transported to the evaluation period under drift.",
                               "No observed-run or CID session model is assumed."]}
